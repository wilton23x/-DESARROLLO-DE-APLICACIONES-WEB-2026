# Requisitos para iniciar el proyecto:

# 1. Crear carpeta del proyecto:
#    mkdir Proyecto

# 2. Ingresar a la carpeta:
#    cd Proyecto

# 3. Instalar virtualenv (si no está instalado):
#    pip install virtualenv

# 4. Crear entorno virtual:
#    python -m venv venv

# 5. Activar entorno virtual:
#    Windows:
#    .\venv\Scripts\activate
#
#    Linux / Mac:
#    source venv/bin/activate

# 6. Instalar Flask:
#    pip install flask

# 7. Ejecutar la aplicación Flask:
#    python app.py

# 8. Abrir navegador y acceder a:
#    http://localhost:5000/
